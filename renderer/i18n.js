  const read = (k) => { try { return localStorage.getItem(k) } catch { return null } }
  const write = (k, v) => { try { localStorage.setItem(k, v) } catch {} }
  function resolveInitial () {
    const saved = read('milpa.locale')
    if (saved === 'en' || saved === 'es') return saved
    if (saved === 'system') {                       // opt-in: follow the OS locale
      const sys = (navigator.language || 'en').slice(0, 2)
      return messages[sys] ? sys : 'en'
    }
    return 'en'                                     // English-first: the default is English (decisions/0138)
  }
  let locale = resolveInitial()

  function t (key, vars) {
    let s = (messages[locale] && messages[locale][key])
    if (s == null) s = messages.en[key]
    if (s == null) return key
    if (vars) for (const k in vars) s = s.split('{' + k + '}').join(String(vars[k]))
    return s
  }
  function applyI18n (root) {
    root = root || document
    root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n) })
    root.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.setAttribute('placeholder', t(el.dataset.i18nPh)) })
    root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.setAttribute('title', t(el.dataset.i18nTitle)) })
    document.documentElement.lang = locale
  }
  function setLocale (l) {
    if (l === 'system') { write('milpa.locale', 'system'); locale = resolveInitial() }
    else { locale = messages[l] ? l : 'en'; write('milpa.locale', locale) }
    applyI18n()
    try { window.dispatchEvent(new CustomEvent('milpa:locale', { detail: locale })) } catch {}
  }
  window.milpaI18n = { t, setLocale, applyI18n, get locale () { return locale } }
  document.addEventListener('DOMContentLoaded', () => applyI18n())
